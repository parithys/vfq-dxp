#!/usr/bin/env python3
"""Builds public/config/query-issues.json from the Ticket Type Categorization workbook (sheets 'List of Issue,SLA,LOV'
and 'Ticket Type Preview Details'). Usage: python3 reference/scripts/build_query_issues.py <path-to-xlsx>"""
import json, re, sys, warnings, openpyxl
warnings.filterwarnings('ignore')
src = sys.argv[1]
wb = openpyxl.load_workbook(src, read_only=True)
norm_type = lambda t: {'Fixed/5G Request': 'Fixed/5G Requests'}.get(t, t)

issues, seen = [], {}
siebel = {r[0] for r in wb['Actual Issue'].iter_rows(min_row=2, values_only=True) if r[0]}
for r in list(wb['List of Issue,SLA,LOV'].iter_rows(values_only=True))[1:]:
    if not r[2]:
        continue
    base = 'QI-' + re.sub(r'[^A-Z0-9]+', '-', r[2].upper()).strip('-')
    n = seen.get(base, 0); seen[base] = n + 1
    e = {'id': base if n == 0 else f'{base}-{n+1}', 'name': r[2], 'category': r[0], 'serviceType': norm_type(r[1])}
    # Routing: the workbook's own words become a rule kind the app can evaluate.
    rt = (r[16] or r[17] or '').strip()
    kind = ('onshore-offshore' if rt.startswith('Expat') else 'collections' if rt.startswith('Collections') else 'number-management' if rt.startswith('Number Management')
            else 'outlet' if rt.startswith('based on outlet') else None)
    if kind: e['routing'] = kind
    for k, i in (('severity', 5), ('severityComment', 7), ('summary', 3), ('subSummary', 4), ('ticketCategory', 9), ('area', 10), ('subArea', 11)):
        if r[i] and r[i] != 'N/A': e[k] = r[i]
    actual = r[18] or (r[2] if r[2] in siebel else None)
    if actual: e['ticketActualIssue'] = actual
    issues.append(e)

rows = list(wb['Ticket Type Preview Details'].iter_rows(values_only=True))
cats, svcs = rows[3], rows[4]
cols, cur = [], None
for i in range(2, 15):
    cur = cats[i] or cur
    cols.append({'category': cur, 'serviceType': norm_type(svcs[i]), 'fields': []})
for r in rows[5:]:
    if not r[0] or r[0] == 'Service Type':
        continue
    for j, c in enumerate(cols):
        if r[2 + j] == 'Y':
            c['fields'].append(r[0])
out = {
    '_note': 'Generated by reference/scripts/build_query_issues.py from Ticket Type Categorization_DRAFT.xlsx (customer-supplied draft, 2026-10-05). issues: Query Issue -> Query Category / Query Service Type / ticket classification. preview: per Query Category + Query Service Type, the ordered Details fields the Preview shows. Do not hand-edit.',
    'categories': sorted({i['category'] for i in issues}),
    'examples': ['Calls', 'Data + Roaming', 'Data', 'Billing', 'SIM', 'Plan'],
    'issues': issues,
    'preview': cols,
}
json.dump(out, open('public/config/query-issues.json', 'w'), indent=1, ensure_ascii=False)
print(len(issues), 'issues;', len(cols), 'preview columns;', sum(len(c['fields']) for c in cols), 'field entries')
